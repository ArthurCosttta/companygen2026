import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import JSZip from 'jszip';

test.describe('Export Functionality & Packaging', () => {
  test('opens export dialog and shows full campaign and post options', async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto('/');
    await expect(page.locator('text=CompanyGen')).toBeVisible({ timeout: 15000 });

    const exportBtn = page.locator('button:has-text("Exportar")').first();
    await expect(exportBtn).toBeVisible({ timeout: 15000 });
    await exportBtn.click();

    // Check dialog content
    await expect(page.locator('text=Exportar Posts e Campanha')).toBeVisible();
    await expect(page.locator('text=Campanha Completa (ZIP)')).toBeVisible();
    await expect(page.locator('text=Post Selecionado (ZIP)')).toBeVisible();
  });

  test('validates generated export package ZIP structure and files', async () => {
    const zipPath = path.resolve('examples/exported_samples/COMPANYGEN_campanha_novembro.zip');
    if (!fs.existsSync(zipPath)) {
      // If not yet generated by script, skip this check
      return;
    }

    const zipData = fs.readFileSync(zipPath);
    const zip = await JSZip.loadAsync(zipData);

    // Verify ZIP contains root files
    expect(zip.file('COMPANYGEN_CAMPAIGN/campaign.json')).toBeDefined();
    expect(zip.file('COMPANYGEN_CAMPAIGN/schedule.csv')).toBeDefined();
    expect(zip.file('COMPANYGEN_CAMPAIGN/assets_manifest.json')).toBeDefined();
    expect(zip.file('COMPANYGEN_CAMPAIGN/credits.md')).toBeDefined();
    expect(zip.file('COMPANYGEN_CAMPAIGN/README.md')).toBeDefined();

    // Verify posts folder
    expect(zip.file('COMPANYGEN_CAMPAIGN/posts/post_001/caption.txt')).toBeDefined();
    expect(zip.file('COMPANYGEN_CAMPAIGN/posts/post_001/slide_01.png')).toBeDefined();
    expect(zip.file('COMPANYGEN_CAMPAIGN/posts/post_001/slide_02.png')).toBeDefined();
  });
});
